async function saveProduct(event) {
  event.preventDefault();
  if (!productForm.reportValidity()) return;

  const id = productForm.elements.namedItem("id").value;
  const errorNode = document.getElementById("product-form-error");
  const submit = document.getElementById("save-product");
  errorNode.hidden = true;
  if (retainedProductImages.length + pendingProductImages.length === 0) {
    errorNode.textContent = adminText("noProductPhotos");
    errorNode.hidden = false;
    return;
  }
  if (retainedProductImages.length + pendingProductImages.length > 5) {
    errorNode.textContent = adminText("productPhotoHint");
    errorNode.hidden = false;
    return;
  }
  if (pendingProductImages.some((file) => file.size > 3 * 1024 * 1024)
    || pendingProductImages.reduce((total, file) => total + file.size, 0) > 4 * 1024 * 1024) {
    errorNode.textContent = adminText("productPhotoHint");
    errorNode.hidden = false;
    return;
  }

  submit.disabled = true;
  try {
    const body = new FormData();
    body.append("product", JSON.stringify(collectProductForm()));
    body.append("existingImages", JSON.stringify(retainedProductImages));
    pendingProductImages.forEach((file) => body.append("images", file));
    await requestJson(id ? `${adminEndpoints.products}/${encodeURIComponent(id)}` : adminEndpoints.products, {
      method: id ? "PUT" : "POST",
      body
    });
    productDialog.close();
    await loadSection(adminEndpoints.products, renderProducts, "products-error", "productsError");
    const status = document.getElementById("product-status");
    status.textContent = adminText("productSaved");
    status.hidden = false;
    window.setTimeout(() => { status.hidden = true; }, 3500);
  } catch (error) {
    if (error.authRequired) {
      productDialog.close();
      dashboard.hidden = true;
      setAccessState("accessRequired");
      return;
    }
    console.error("Unable to save product.", error);
    errorNode.textContent = error.message || adminText("productSaveError");
    errorNode.hidden = false;
  } finally {
    submit.disabled = false;
  }
}

