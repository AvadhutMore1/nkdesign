function updateCartCount(value) {
  const count = Number.parseInt(value, 10);
  const safeCount = Number.isFinite(count) && count >= 0 ? count : 0;
  cartCount.textContent = String(safeCount);
  bagLink.setAttribute("aria-label", document.documentElement.lang === "mr" ? `शॉपिंग बॅग, ${safeCount} वस्तू` : `Shopping bag, ${safeCount} items`);
  cartCount.classList.remove("is-updated");
  requestAnimationFrame(() => cartCount.classList.add("is-updated"));
}

window.addEventListener("storage", (event) => {
  if (event.key === "nk-design-cart-count" && event.newValue !== null) updateCartCount(event.newValue);
});
window.addEventListener("nk-design:cart-update", (event) => {
  if (event.detail && typeof event.detail.count === "number") updateCartCount(event.detail.count);
});

if ("IntersectionObserver" in window && !prefersReducedMotion) {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  document.querySelectorAll(".reveal").forEach((element) => revealObserver.observe(element));
} else {
  document.querySelectorAll(".reveal").forEach((element) => element.classList.add("is-visible"));
}

