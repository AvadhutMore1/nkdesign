document.querySelectorAll("[data-image-key]").forEach((element) => {
  const assetKey = element.dataset.imageKey;
  const assetUrl = configuredAssets[assetKey] || defaultAssets[assetKey];
  if (!assetUrl) return;
  if (element instanceof HTMLImageElement) {
    element.src = assetUrl;
  } else if (element.classList.contains("collection-card")) {
    const image = element.querySelector("img");
    if (image) image.src = assetUrl;
  } else if (assetKey === "hero") {
    element.style.setProperty("--hero-image", `url("${assetUrl}")`);
  } else if (assetKey === "customBackdrop") {
    element.style.setProperty("--custom-image", `url("${assetUrl}")`);
  }
});

function setLanguage(language) {
  const selectedLanguage = translations[language] ? language : "en";
  document.documentElement.lang = selectedLanguage;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = translations[selectedLanguage][element.dataset.i18n];
    if (translation) element.innerHTML = translation;
  });
  languageOptions.forEach((option) => {
    const isSelected = option.dataset.language === selectedLanguage;
    option.classList.toggle("is-selected", isSelected);
    option.setAttribute("aria-pressed", String(isSelected));
  });
  try {
    localStorage.setItem("nk-design-language", selectedLanguage);
  } catch (error) {
    console.warn("Could not save the selected language.", error);
  }
  window.dispatchEvent(new CustomEvent("nk-design:language-change", { detail: { language: selectedLanguage } }));
}

function closeMenu() {
  navContent.classList.remove("is-open");
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", document.documentElement.lang === "mr" ? "मेनू उघडा" : "Open menu");
}

languageOptions.forEach((option) => {
  option.addEventListener("click", () => setLanguage(option.dataset.language));
});

menuToggle.addEventListener("click", () => {
  const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!isOpen));
  menuToggle.setAttribute("aria-label", isOpen ? "Open menu" : "Close menu");
  navContent.classList.toggle("is-open", !isOpen);
});

navContent.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && navContent.classList.contains("is-open")) {
    closeMenu();
    menuToggle.focus();
  }
});
window.addEventListener("resize", () => {
  if (window.innerWidth > 760) closeMenu();
});

