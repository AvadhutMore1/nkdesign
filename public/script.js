const collectionGrid = document.getElementById("collection-grid");
let liveCollections = null;

function collectionImageUrl(value) {
  if (typeof value !== "string" || !value.trim()) return "";
  try {
    const url = new URL(value, window.location.href);
    return url.protocol === "https:" ? url.href : "";
  } catch {
    return "";
  }
}

function renderLiveCollections(language = document.documentElement.lang) {
  if (!collectionGrid || !Array.isArray(liveCollections)) return;
  collectionGrid.replaceChildren();

  liveCollections.forEach((collection, index) => {
    const card = document.createElement("a");
    card.className = "collection-card reveal is-visible";
    if (liveCollections.length > 2 && index === 0) card.classList.add("collection-card-tall");
    if (liveCollections.length >= 6 && index === 4) card.classList.add("collection-card-wide");
    const category = language === "mr" && collection.categoryMr ? collection.categoryMr : collection.category;
    const name = language === "mr" && collection.nameMr ? collection.nameMr : collection.name;
    const description = language === "mr" && collection.descriptionMr ? collection.descriptionMr : collection.description;
    card.href = `shop.html?category=${encodeURIComponent(collection.category || "")}`;

    const image = document.createElement("img");
    image.src = collectionImageUrl(collection.coverImage)
      || "https://images.unsplash.com/photo-1610030469983-98e550d6193c?auto=format&fit=crop&w=1200&q=85";
    image.alt = name || category || "NK Design collection";
    image.loading = "lazy";

    const number = document.createElement("span");
    number.className = "collection-number";
    number.textContent = String(index + 1).padStart(2, "0");

    const overlay = document.createElement("span");
    overlay.className = "collection-overlay";

    const caption = document.createElement("span");
    caption.className = "collection-caption glass-card";
    const copy = document.createElement("span");
    copy.className = "collection-copy";
    const kicker = document.createElement("span");
    kicker.className = "collection-kicker";
    kicker.textContent = category || "NK DESIGN";
    const title = document.createElement("strong");
    title.textContent = name || category || "NK Design";
    const summary = document.createElement("span");
    summary.textContent = description || "";
    copy.append(kicker, title, summary);

    const arrow = document.createElement("span");
    arrow.className = "collection-arrow";
    arrow.setAttribute("aria-hidden", "true");
    arrow.textContent = "↗";
    caption.append(copy, arrow);
    card.append(image, number, overlay, caption);
    collectionGrid.append(card);
  });
}

if (collectionGrid) {
  fetch("/api/collections", { headers: { Accept: "application/json" } })
    .then((response) => {
      if (!response.ok) throw new Error(`Collection request failed with status ${response.status}.`);
      return response.json();
    })
    .then((payload) => {
      const records = Array.isArray(payload) ? payload : payload && payload.collections;
      if (!Array.isArray(records)) throw new Error("Collection API response did not contain a collections array.");
      liveCollections = records.filter((collection) => collection && collection.active !== false);
      renderLiveCollections();
    })
    .catch((error) => console.warn("Unable to load live NK Design collections.", error));
}

window.addEventListener("nk-design:language-change", (event) => {
  renderLiveCollections(event.detail && event.detail.language);
});

async function addAccountAction() {
  const navActions = document.querySelector(".nav-actions");
  if (!navActions) return;

  try {
    const adminResponse = await fetch("/api/admin/session", { credentials: "same-origin" });
    if (adminResponse.ok) {
      const link = document.createElement("a");
      link.className = "account-action";
      link.href = "/admin.html";
      link.textContent = "Studio admin";
      navActions.prepend(link);
      return;
    }

    const customerResponse = await fetch("/api/customer/session", { credentials: "same-origin" });
    if (!customerResponse.ok) return;
    const customerSession = await customerResponse.json();
    const signOut = document.createElement("button");
    signOut.className = "account-action";
    signOut.type = "button";
    signOut.textContent = `Sign out${customerSession.user && customerSession.user.name ? `, ${customerSession.user.name}` : ""}`;
    signOut.addEventListener("click", async () => {
      signOut.disabled = true;
      try {
        const response = await fetch("/api/customer/logout", {
          method: "POST",
          credentials: "same-origin",
          headers: { Accept: "application/json" }
        });
        if (!response.ok) throw new Error(`Sign-out failed (${response.status}).`);
        window.location.assign("/login.html");
      } catch (error) {
        console.error("Unable to sign out of the NK Design customer account.", error);
        signOut.disabled = false;
        window.alert("Could not sign out. Please try again.");
      }
    });
    navActions.prepend(signOut);
  } catch (error) {
    console.error("Unable to check the NK Design account session.", error);
  }
}

addAccountAction();
