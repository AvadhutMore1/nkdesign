function cartLanguage() {
  return document.documentElement.lang === "mr" ? "mr" : "en";
}

function cartText(key, ...args) {
  const value = cartTranslations[cartLanguage()][key];
  return typeof value === "function" ? value(...args) : value || cartTranslations.en[key] || key;
}

function applyCartLanguage() {
  document.querySelectorAll("[data-cart-i18n]").forEach((element) => {
    const value = cartTranslations[cartLanguage()][element.dataset.cartI18n];
    if (typeof value === "string") element.innerHTML = value;
  });
  document.querySelectorAll("[data-cart-placeholder]").forEach((element) => {
    const value = cartTranslations[cartLanguage()][element.dataset.cartPlaceholder];
    if (value) element.placeholder = value;
  });
  renderCart();
  updateCheckoutState();
}

window.addEventListener("nk-design:language-change", applyCartLanguage);

function parseSavedCart() {
  const raw = localStorage.getItem("nk-design-cart");
  if (!raw) return [];
  const parsed = JSON.parse(raw);
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) throw new Error("Saved cart format is invalid");
  return Object.entries(parsed).map(([key, value]) => {
    if (!value || typeof value !== "object") throw new Error("Saved cart item is invalid");
    const id = String(value.productId || key.split(":")[0] || "");
    const quantity = Number(value.quantity);
    const price = Number(value.price);
    if (!id || !Number.isInteger(quantity) || quantity < 1 || !Number.isFinite(price) || price < 0) {
      throw new Error("Saved cart item contains invalid values");
    }
    let image = "";
    try {
      if (typeof value.image === "string" && value.image) {
        const url = new URL(value.image, window.location.href);
        if (["https:", "http:"].includes(url.protocol)) image = url.href;
      }
    } catch (error) {
      console.warn("Ignoring an invalid product image in the saved cart.", error);
    }
    return {
      key,
      productId: id,
      name: typeof value.name === "string" ? value.name : "NK Design",
      nameMr: typeof value.nameMr === "string" ? value.nameMr : "",
      image,
      price,
      quantity,
      size: typeof value.size === "string" ? value.size : "",
      color: typeof value.color === "string" ? value.color : ""
    };
  });
}

function currency(value) {
  return new Intl.NumberFormat(cartLanguage() === "mr" ? "mr-IN" : "en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0
  }).format(value);
}

function totalQuantity() {
  return cartItems.reduce((total, item) => total + item.quantity, 0);
}

function subtotal() {
  return cartItems.reduce((total, item) => total + item.price * item.quantity, 0);
}

function updateSavedCart(items) {
  const payload = {};
  items.forEach((item) => {
    payload[item.key] = {
      productId: item.productId,
      name: item.name,
      ...(item.nameMr ? { nameMr: item.nameMr } : {}),
      price: item.price,
      quantity: item.quantity,
      image: item.image,
      ...(item.size ? { size: item.size } : {}),
      ...(item.color ? { color: item.color } : {})
    };
  });
  localStorage.setItem("nk-design-cart", JSON.stringify(payload));
  localStorage.setItem("nk-design-cart-count", String(items.reduce((count, item) => count + item.quantity, 0)));
  window.dispatchEvent(new CustomEvent("nk-design:cart-update", {
    detail: { count: items.reduce((count, item) => count + item.quantity, 0) }
  }));
}

function element(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function renderLineItem(item) {
  const row = element("article", "cart-item");
  const imageFrame = element("div", "cart-item-image");
  if (item.image) {
    const image = element("img");
    image.src = item.image;
    image.alt = item.name;
    image.loading = "lazy";
    imageFrame.append(image);
  } else {
    imageFrame.append(element("span", "cart-image-placeholder", "NK"));
  }

  const details = element("div", "cart-item-details");
  const title = element("h3", "cart-item-title", cartLanguage() === "mr" && item.nameMr ? item.nameMr : item.name);
  const options = element("div", "cart-item-options");
  if (item.size) options.append(element("span", "", `${cartText("size")}: ${item.size}`));
  if (item.color) options.append(element("span", "", `${cartText("color")}: ${item.color}`));
  const unitPrice = element("p", "cart-item-unit-price", currency(item.price));
  details.append(title, options, unitPrice);

  const controls = element("div", "cart-item-controls");
  const quantity = element("div", "quantity-control");
  quantity.setAttribute("aria-label", `${item.name} — ${cartText("items")}`);
  const decrease = element("button", "", "−");
  decrease.type = "button";
  decrease.setAttribute("aria-label", cartLanguage() === "mr" ? "एक वस्तू कमी करा" : "Decrease quantity");
  decrease.dataset.cartAction = "decrease";
  decrease.dataset.cartKey = item.key;
  const quantityValue = element("span", "quantity-value", String(item.quantity));
  quantityValue.setAttribute("aria-live", "polite");
  const increase = element("button", "", "+");
  increase.type = "button";
  increase.setAttribute("aria-label", cartLanguage() === "mr" ? "एक वस्तू वाढवा" : "Increase quantity");
  increase.dataset.cartAction = "increase";
  increase.dataset.cartKey = item.key;
  quantity.append(decrease, quantityValue, increase);
  const lineTotal = element("strong", "cart-item-total", currency(item.price * item.quantity));
  const remove = element("button", "remove-item", cartText("remove"));
  remove.type = "button";
  remove.dataset.cartAction = "remove";
  remove.dataset.cartKey = item.key;
  controls.append(quantity, lineTotal, remove);

  row.append(imageFrame, details, controls);
  return row;
}

function renderCart() {
  cartLoading.hidden = true;
  cartLayout.hidden = false;
  cartItemsContainer.replaceChildren();
  if (cartHasError) {
    cartItemsContainer.hidden = false;
    cartItemsContainer.append(element("p", "cart-read-error", cartText("invalidCart")));
    cartEmpty.hidden = true;
    itemCount.textContent = "";
    updateSummary();
    checkoutAction.disabled = true;
    return;
  }
  const isEmpty = cartItems.length === 0;
  cartEmpty.hidden = !isEmpty;
  document.querySelector(".continue-shopping").hidden = isEmpty;
  cartItemsContainer.hidden = isEmpty;
  if (!isEmpty) cartItems.forEach((item) => cartItemsContainer.append(renderLineItem(item)));
  const count = totalQuantity();
  itemCount.textContent = `${count} ${count === 1 ? cartText("item") : cartText("items")}`;
  checkoutAction.disabled = isEmpty || isSubmittingOrder;
  updateSummary();
}

function updateSummary() {
  const amount = subtotal();
  subtotalElement.textContent = currency(amount);
  totalElement.textContent = currency(amount);
}

function showCheckoutError(message, summary = false) {
  const target = summary ? summaryError : checkoutError;
  target.textContent = message;
  target.hidden = false;
  target.focus?.();
}

function clearCheckoutError() {
  checkoutError.hidden = true;
  summaryError.hidden = true;
}

function updateCheckoutState() {
  checkoutPanel.hidden = !checkoutIsOpen;
  document.querySelector(".checkout-step").classList.toggle("is-active", !checkoutIsOpen);
  document.querySelector(".checkout-step").classList.toggle("is-complete", checkoutIsOpen);
  detailsStep.classList.toggle("is-active", checkoutIsOpen);
  detailsStep.classList.toggle("is-complete", checkoutIsOpen && cartItems.length > 0);
  if (checkoutIsOpen) detailsStep.setAttribute("aria-current", "step");
  else detailsStep.removeAttribute("aria-current");
  confirmStep.classList.remove("is-active", "is-complete");
  confirmStep.removeAttribute("aria-current");
  checkoutActionLabel.textContent = cartText(checkoutIsOpen ? "goToDetails" : "proceed");
  document.querySelector(".cart-content").classList.toggle("is-checkout-open", checkoutIsOpen);
}

function changeQuantity(key, amount) {
  const item = cartItems.find((entry) => entry.key === key);
  if (!item) {
    showCheckoutError(cartText("unavailable"), true);
    return;
  }
  const quantity = item.quantity + amount;
  try {
    const updated = quantity > 0
      ? cartItems.map((entry) => entry.key === key ? { ...entry, quantity } : entry)
      : cartItems.filter((entry) => entry.key !== key);
    updateSavedCart(updated);
    cartItems = updated;
    clearCheckoutError();
    renderCart();
  } catch (error) {
    console.error("Unable to update the NK Design cart.", error);
    showCheckoutError(cartText("quantityError"), true);
  }
}

cartItemsContainer.addEventListener("click", (event) => {
  const button = event.target.closest("button[data-cart-action]");
  if (!button) return;
  const key = button.dataset.cartKey;
  if (button.dataset.cartAction === "increase") changeQuantity(key, 1);
  if (button.dataset.cartAction === "decrease") changeQuantity(key, -1);
  if (button.dataset.cartAction === "remove") {
    try {
      const updated = cartItems.filter((item) => item.key !== key);
      updateSavedCart(updated);
      cartItems = updated;
      renderCart();
    } catch (error) {
      console.error("Unable to remove the item from the NK Design cart.", error);
      showCheckoutError(cartText("quantityError"), true);
    }
  }
});

checkoutAction.addEventListener("click", () => {
  clearCheckoutError();
  if (!cartItems.length) {
    showCheckoutError(cartText("emptyOrder"), true);
    return;
  }
  if (!checkoutIsOpen) {
    checkoutIsOpen = true;
    updateCheckoutState();
    checkoutPanel.scrollIntoView({ behavior: "smooth", block: "start" });
    return;
  }
  checkoutPanel.scrollIntoView({ behavior: "smooth", block: "start" });
  checkoutForm.elements.namedItem("customerName").focus({ preventScroll: true });
});

checkoutForm.addEventListener("submit", (event) => {
  event.preventDefault();
  clearCheckoutError();
  const firstInvalid = Array.from(checkoutForm.querySelectorAll("input, textarea")).find((field) => !field.checkValidity());
  if (firstInvalid) {
    firstInvalid.reportValidity();
    const message = firstInvalid.name === "phone"
      ? cartText("phoneError")
      : firstInvalid.name === "postalCode"
        ? cartText("pinError")
        : firstInvalid.name === "paymentMethod"
          ? cartText("paymentError")
          : cartText("requiredError");
    showCheckoutError(message);
    firstInvalid.focus();
    return;
  }
  const paymentMethod = checkoutForm.elements.namedItem("paymentMethod").value;
  if (!paymentMethod) {
    showCheckoutError(cartText("paymentError"));
    return;
  }
  placeOrder(paymentMethod);
});

checkoutForm.addEventListener("input", () => {
  checkoutError.hidden = true;
  summaryError.hidden = true;
});
checkoutForm.addEventListener("change", () => {
  checkoutError.hidden = true;
  summaryError.hidden = true;
});

async function placeOrder(paymentMethod) {
  if (isSubmittingOrder) return;
  if (!cartItems.length) {
    showCheckoutError(cartText("emptyOrder"), true);
    return;
  }
  isSubmittingOrder = true;
  checkoutAction.disabled = true;
  checkoutSubmit.disabled = true;
  checkoutActionLabel.textContent = cartText("submitting");
  checkoutSubmit.querySelector("span").textContent = cartText("submitting");
  clearCheckoutError();
  const payload = {
    customer: {
      name: checkoutForm.elements.namedItem("customerName").value.trim(),
      phone: checkoutForm.elements.namedItem("phone").value.trim(),
      email: checkoutForm.elements.namedItem("email").value.trim(),
      address: checkoutForm.elements.namedItem("address").value.trim(),
      city: checkoutForm.elements.namedItem("city").value.trim(),
      state: checkoutForm.elements.namedItem("state").value.trim(),
      postalCode: checkoutForm.elements.namedItem("postalCode").value.trim(),
      country: checkoutForm.elements.namedItem("country").value.trim(),
      notes: checkoutForm.elements.namedItem("notes").value.trim()
    },
    items: cartItems.map((item) => ({
      productId: item.productId,
      quantity: item.quantity,
      ...(item.size ? { size: item.size } : {}),
      ...(item.color ? { color: item.color } : {})
    })),
    paymentMethod,
    language: cartLanguage()
  };
  try {
    const response = await fetch(orderEndpoint, {
      method: "POST",
      headers: { "Content-Type": "application/json", Accept: "application/json" },
      body: JSON.stringify(payload)
    });
    const result = await response.json().catch(() => null);
    if (!response.ok) throw new Error(`Order request failed (${response.status}): ${result?.message || response.statusText}`);
    if (!result || typeof result !== "object") throw new Error("Order API returned an invalid response");

    if (paymentMethod === "online") {
      if (result.paymentUrl) {
        const paymentUrl = new URL(result.paymentUrl, window.location.origin);
        if (!["https:", "http:"].includes(paymentUrl.protocol) || (paymentUrl.protocol === "http:" && paymentUrl.origin !== window.location.origin)) {
          throw new Error("Order API returned an unsafe payment URL");
        }
        window.location.assign(paymentUrl.href);
        return;
      }
      if (!["paid", "confirmed"].includes(result.status)) {
        showCheckoutError(cartText("paymentUnavailable"));
        return;
      }
    } else if (!["pending", "confirmed", "paid", "processing"].includes(result.status)) {
      throw new Error("Order API did not confirm that it received the order");
    }

    try {
      localStorage.removeItem("nk-design-cart");
      localStorage.setItem("nk-design-cart-count", "0");
    } catch (storageError) {
      console.error("The order was received, but the saved bag could not be cleared.", storageError);
    }
    window.dispatchEvent(new CustomEvent("nk-design:cart-update", { detail: { count: 0 } }));
    orderReference.textContent = result.orderNumber || result.orderId || result.id
      ? cartText("reference", String(result.orderNumber || result.orderId || result.id))
      : "";
    cartLayout.hidden = true;
    orderSuccess.hidden = false;
    document.querySelector(".checkout-step").classList.remove("is-active");
    document.querySelector(".checkout-step").classList.add("is-complete");
    detailsStep.classList.remove("is-active");
    detailsStep.classList.add("is-complete");
    confirmStep.classList.add("is-active");
    confirmStep.setAttribute("aria-current", "step");
    orderSuccess.focus();
  } catch (error) {
    console.error("Unable to place the NK Design order.", error);
    showCheckoutError(error instanceof TypeError ? cartText("networkError") : cartText("orderError"));
  } finally {
    isSubmittingOrder = false;
    checkoutSubmit.disabled = false;
    checkoutSubmit.querySelector("span").textContent = cartText("placeOrder");
    if (!orderSuccess.hidden) {
      checkoutAction.disabled = true;
    } else {
      checkoutAction.disabled = cartItems.length === 0;
      checkoutActionLabel.textContent = cartText(checkoutIsOpen ? "placeOrder" : "proceed");
    }
  }
}

window.addEventListener("storage", (event) => {
  if (event.key === "nk-design-cart" || event.key === "nk-design-cart-count") loadCart();
});
window.addEventListener("nk-design:cart-update", () => loadCart());

function loadCart() {
  cartHasError = false;
  try {
    cartItems = parseSavedCart();
  } catch (error) {
    console.error("Unable to read the saved NK Design cart.", error);
    cartItems = [];
    cartHasError = true;
  }
  renderCart();
  updateCheckoutState();
}

