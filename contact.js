const contactForm = document.getElementById("contact-form");
const contactFormCard = document.getElementById("contact-form-card");
const contactError = document.getElementById("contact-error");
const contactSubmit = document.querySelector(".contact-submit");
const messageField = contactForm.elements.namedItem("message");
const messageCount = document.getElementById("message-count");
const whatsappLink = document.getElementById("contact-whatsapp");
const contactEndpoint = window.NK_DESIGN_API && window.NK_DESIGN_API.contactUrl
  ? window.NK_DESIGN_API.contactUrl
  : "/api/contact-inquiries";
const whatsappNumber = typeof window.NK_DESIGN_WHATSAPP === "string"
  ? window.NK_DESIGN_WHATSAPP.replace(/\D/g, "")
  : "";

function contactLanguage() {
  return document.documentElement.lang === "mr" ? "mr" : "en";
}

function contactText(key, ...args) {
  const value = contactTranslations[contactLanguage()][key];
  return typeof value === "function" ? value(...args) : value || contactTranslations.en[key] || key;
}

function applyContactLanguage() {
  document.querySelectorAll("[data-contact-i18n]").forEach((node) => {
    const value = contactTranslations[contactLanguage()][node.dataset.contactI18n];
    if (typeof value === "string") node.innerHTML = value;
  });
  document.querySelectorAll("[data-contact-placeholder]").forEach((node) => {
    const value = contactTranslations[contactLanguage()][node.dataset.contactPlaceholder];
    if (value) node.placeholder = value;
  });
  updateMessageCount();
  updateWhatsappLink();
}

window.addEventListener("nk-design:language-change", applyContactLanguage);

function updateMessageCount() {
  messageCount.textContent = contactText("messageCount", messageField.value.length, messageField.maxLength);
}

function showContactError(message) {
  contactError.textContent = message;
  contactError.hidden = false;
  contactError.focus();
}

function showContactSuccess() {
  const heading = document.createElement("h2");
  heading.className = "contact-success-title";
  heading.tabIndex = -1;
  heading.dataset.contactI18n = "successTitle";
  const eyebrow = document.createElement("p");
  eyebrow.className = "eyebrow eyebrow-dark";
  const line = document.createElement("span");
  line.className = "eyebrow-line";
  const label = document.createElement("span");
  label.dataset.contactI18n = "successEyebrow";
  eyebrow.append(line, label);
  const description = document.createElement("p");
  description.className = "contact-success-description";
  description.dataset.contactI18n = "successBody";
  contactFormCard.replaceChildren(eyebrow, heading, description);
  applyContactLanguage();
  heading.focus();
}

function validatePhone() {
  const phone = contactForm.elements.namedItem("phone");
  phone.setCustomValidity(phone.value && phone.validity.patternMismatch ? contactText("phoneError") : "");
}

contactForm.elements.namedItem("phone").addEventListener("input", validatePhone);
messageField.addEventListener("input", updateMessageCount);
contactForm.addEventListener("input", () => { contactError.hidden = true; });
contactForm.addEventListener("change", () => { contactError.hidden = true; });

contactForm.addEventListener("submit", async (event) => {
  event.preventDefault();
  contactError.hidden = true;
  validatePhone();
  const invalid = Array.from(contactForm.querySelectorAll("input, select, textarea")).find((field) => !field.checkValidity());
  if (invalid) {
    invalid.reportValidity();
    const message = invalid.name === "email"
      ? contactText("emailError")
      : invalid.name === "phone"
        ? contactText("phoneError")
        : invalid.name === "contactConsent"
          ? contactText("consentError")
          : contactText("requiredError");
    showContactError(message);
    invalid.focus();
    return;
  }

  const buttonText = contactSubmit.querySelector("span");
  contactSubmit.disabled = true;
  buttonText.textContent = contactText("sending");
  const formData = new FormData(contactForm);
  formData.set("language", contactLanguage());
  try {
    const response = await fetch(contactEndpoint, {
      method: "POST",
      headers: { Accept: "application/json" },
      body: formData
    });
    if (!response.ok) {
      const detail = await response.text();
      throw new Error(`Contact enquiry request failed (${response.status}): ${detail.slice(0, 300)}`);
    }
    showContactSuccess();
  } catch (error) {
    console.error("Unable to send the NK Design contact enquiry.", error);
    showContactError(error instanceof TypeError ? contactText("networkError") : contactText("sendError"));
  } finally {
    contactSubmit.disabled = false;
    buttonText.textContent = contactText("submit");
  }
});

function updateWhatsappLink() {
  if (whatsappNumber) {
    const message = contactLanguage() === "mr"
      ? "नमस्कार NK Design, मला एक प्रश्न विचारायचा आहे."
      : "Hello NK Design, I have a question.";
    whatsappLink.href = `https://wa.me/${whatsappNumber}?text=${encodeURIComponent(message)}`;
  }
}

if (whatsappNumber) {
  whatsappLink.hidden = false;
}

applyContactLanguage();
