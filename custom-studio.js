  const review = document.getElementById("review-list");
  review.replaceChildren();
  const measurements = [
    ["bust", "bustLabel"],
    ["underBust", "underBustLabel"],
    ["shoulder", "shoulderLabel"],
    ["length", "blouseLengthLabel"],
    ["sleeveLength", "sleeveLengthLabel"]
  ].map(([name, label]) => {
    const value = fieldValue(`measurements[${name}]`);
    return value ? `${studioText(label)}: ${value} ${studioText("cm")}` : "";
  }).filter(Boolean).join(" · ");
  const fileNames = Array.from(fileInput.files).map((file) => file.name).join(", ") || studioText("noFiles");
