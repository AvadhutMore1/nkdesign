const previewUrls = new Map();

function studioLanguage() {
  return document.documentElement.lang === "mr" ? "mr" : "en";
}

function studioText(key) {
  return studioTranslations[studioLanguage()][key] || studioTranslations.en[key] || key;
}

function applyStudioLanguage(language = studioLanguage()) {
  const dictionary = studioTranslations[language] || studioTranslations.en;
  document.querySelectorAll("[data-studio-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.studioI18n];
    if (typeof value === "string") element.innerHTML = value;
  });
  document.querySelectorAll("[data-studio-placeholder]").forEach((element) => {
    const value = dictionary[element.dataset.studioPlaceholder];
    if (value) element.placeholder = value;
  });
  updateStepView();
  if (!successCard.hidden) renderReview();
}

window.addEventListener("nk-design:language-change", (event) => {
  applyStudioLanguage(event.detail && event.detail.language ? event.detail.language : studioLanguage());
});

function updateStepView() {
  studioSteps.forEach((step, index) => {
    step.hidden = index !== currentStep;
    const kicker = step.querySelector(".step-kicker");
    if (kicker) kicker.textContent = `${studioText("stepLabel")} ${String(index + 1).padStart(2, "0")}`;
  });
  stepIndicators.forEach((indicator, index) => {
    indicator.classList.toggle("is-current", index === currentStep);
    indicator.classList.toggle("is-complete", index < currentStep);
    if (index === currentStep) indicator.setAttribute("aria-current", "step");
    else indicator.removeAttribute("aria-current");
  });
  progressFill.style.width = `${(currentStep / (studioSteps.length - 1)) * 100}%`;
  stepCount.textContent = `${String(currentStep + 1).padStart(2, "0")} / ${String(studioSteps.length).padStart(2, "0")}`;
  backButton.hidden = currentStep === 0;
  nextButton.hidden = currentStep === studioSteps.length - 1;
  submitButton.hidden = currentStep !== studioSteps.length - 1;
  formError.hidden = true;
}

function showFormError(message) {
  formError.textContent = message;
  formError.hidden = false;
  formError.focus();
}

function validateCurrentStep() {
  const activeStep = studioSteps[currentStep];
  updatePhoneValidity();
  const invalid = Array.from(activeStep.querySelectorAll("input, select, textarea")).find((field) => !field.checkValidity());
  if (invalid) {
    invalid.reportValidity();
    showFormError(invalid.name === "phone" ? studioText("phoneError") : studioText("requiredError"));
    return false;
  }
  if (currentStep === 4 && !validateImages()) return false;
  return true;
}

function goToStep(index) {
  currentStep = Math.max(0, Math.min(studioSteps.length - 1, index));
  if (currentStep === studioSteps.length - 1) renderReview();
  updateStepView();
  document.querySelector(".studio-topline").scrollIntoView({ behavior: studioReducedMotion ? "auto" : "smooth", block: "start" });
  const heading = studioSteps[currentStep].querySelector("h3");
  if (heading) {
    heading.setAttribute("tabindex", "-1");
    heading.focus({ preventScroll: true });
  }
}

function validateImages() {
  uploadError.hidden = true;
  const files = Array.from(fileInput.files);
  if (files.length > 5) {
    showUploadError("uploadTooMany");
    return false;
  }
  for (const file of files) {
    if (!["image/jpeg", "image/png", "image/webp"].includes(file.type)) {
      showUploadError("uploadInvalid");
      return false;
    }
    if (file.size > 5 * 1024 * 1024) {
      showUploadError("uploadTooLarge");
      return false;
    }
  }
  return true;
}

function showUploadError(key) {
  uploadError.textContent = studioText(key);
  uploadError.hidden = false;
}

function clearImagePreviews() {
  previewUrls.forEach((url) => URL.revokeObjectURL(url));
  previewUrls.clear();
  imagePreviews.replaceChildren();
}

function renderImagePreviews() {
  clearImagePreviews();
  Array.from(fileInput.files).forEach((file, index) => {
    const url = URL.createObjectURL(file);
    previewUrls.set(file, url);
    const preview = document.createElement("div");
    preview.className = "image-preview";
    const image = document.createElement("img");
    image.src = url;
    image.alt = file.name;
    const remove = document.createElement("button");
    remove.type = "button";
    remove.className = "image-preview-remove";
    remove.textContent = "×";
    remove.setAttribute("aria-label", studioLanguage() === "mr" ? `${file.name} काढा` : `Remove ${file.name}`);
    remove.addEventListener("click", () => removeImage(index));
    preview.append(image, remove);
    imagePreviews.append(preview);
  });
}

function removeImage(index) {
  const files = Array.from(fileInput.files);
  files.splice(index, 1);
  const transfer = new DataTransfer();
  files.forEach((file) => transfer.items.add(file));
  fileInput.files = transfer.files;
  renderImagePreviews();
  validateImages();
}

function fieldValue(name) {
  const element = studioForm.elements.namedItem(name);
  if (!element) return "";
  if (element instanceof RadioNodeList) return element.value || "";
  return element.value.trim();
}

function selectedLabel(name) {
  const field = studioForm.elements.namedItem(name);
  if (field instanceof HTMLSelectElement) return field.selectedOptions[0]?.textContent || "";
  return fieldValue(name);
}

